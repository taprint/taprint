/** 常用 GBK 子集表：Unicode 码点 → [首字节, 次字节]。 */
export const GBK_SUBSET_TABLE: ReadonlyMap<number, readonly [number, number]> = new Map(
  Object.entries(GBK_PAIRS).map(
    ([key, value]) => [Number(key), value] as const,
  ),
);

/**
 * GBK 子集编码：ASCII 原样；表内双字节；表外按策略占位（默认 U+FFFD）。
 * 按 Unicode 码点迭代（代理对合并处理；孤立代理落表外占位）。
 */
export function gbkEncode(text: string, options: GbkEncodeOptions = {}): Uint8Array {
  const unmapped: GbkUnmappedPolicy = options.unmapped ?? 'replacement';
  const parts: Uint8Array[] = [];
  for (const ch of text) {
    const codePoint = ch.codePointAt(0) as number;
    if (codePoint < 0x80) {
      parts.push(new Uint8Array([codePoint]));
      continue;
    }
    const pair = GBK_SUBSET_TABLE.get(codePoint);
    if (pair) {
      parts.push(new Uint8Array([pair[0], pair[1]]));
    } else if (unmapped === 'question') {
      parts.push(new Uint8Array([0x3f]));
    } else {
      parts.push(new Uint8Array(GBK_REPLACEMENT_BYTES));
    }
  }
  return concatBytes(...parts);
}
