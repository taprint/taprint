/** 表外字符默认占位：U+FFFD 的 UTF-8 字节序列。 */
export const GBK_REPLACEMENT_BYTES: readonly number[] = [0xef, 0xbf, 0xbd];

/** 表外字符策略：replacement=U+FFFD（ADR-0009 默认）/ question='?'（Dart 兼容档）。 */
export type GbkUnmappedPolicy = 'replacement' | 'question';

export interface GbkEncodeOptions {
  readonly unmapped?: GbkUnmappedPolicy;
}

