// GBK 系编码通道（ESC/POS / TSPL / CPCL 编码器共用）。
//
// 两张表、两种通道：
// - [GbkFullCodec]：GB18030 双字节区**全表**（gbk_full.dart，自动生成，
//   oracle 锁定）——**编码器默认通道**（ADR-0009：覆盖率由 oracle 生成，
//   不手写）；
// - [GbkCodec] + [gbkTable]：常用字**子集表**，保留为可选 fast path
//   （包体/首载敏感场景）。子集表每项与全表逐字节一致（由
//   test/printers/gbk_subset_test.dart 钉住），两通道对同一字符产出
//   相同字节，仅覆盖率不同。
//
// 编码口径：ASCII（< 0x80）原样单字节；表内字符查表双字节；表外字符
// 折 fallback 字节（默认 '?' = 0x3F）。解码口径（仅全表通道）：字节对
// 不在表内 / 尾部截断 → U+FFFD（ADR-0009 替换语义）。
// encoding='gbk'/'gb2312'/'gb18030' 均按本族双字节表处理。

import 'dart:typed_data';

import 'gbk_full.dart';

/// GBK 系编码通道契约（编码器构造注入，可换实现打桩/扩展）。
abstract interface class GbkEncoder {
  /// 是否 GBK 系编码（ESC/POS 通道据此决定是否发送汉字模式指令）。
  bool get isGbkLike;

  /// 编码字符串为 GBK/GB18030 字节序列。
  Uint8List encode(String s);
}

/// GB18030 双字节区全表通道（编码器默认）。
///
/// 表见 [gbkFullTable]（生成器 tools/gen_gbk_table.py，Python gb18030
/// codec 全区枚举 + 逐对回编校验；oracle 向量在
/// test/fixtures_gbk_oracle.json）。
class GbkFullCodec implements GbkEncoder {
  const GbkFullCodec({this.fallbackByte = 0x3F});

  /// 表外字符的占位字节（默认 ASCII '?'）。
  final int fallbackByte;

  @override
  bool get isGbkLike => true;

  @override
  Uint8List encode(String s) {
    final out = BytesBuilder();
    for (final char in s.runes) {
      if (char < 0x80) {
        out.addByte(char);
        continue;
      }
      final packed = gbkFullTable[char];
      if (packed == null) {
        out.addByte(fallbackByte);
        continue;
      }
      out.addByte((packed >> 8) & 0xFF);
      out.addByte(packed & 0xFF);
    }
    return out.toBytes();
  }

  /// 解码 GBK/GB18030 双字节字节流：
  /// - ASCII（< 0x80）原样字符；
  /// - 表内字节对 → 码点；
  /// - 表外字节对 / 尾部截断的首字节 → U+FFFD（每对/每残字节一个）。
  String decode(List<int> bytes) {
    final sb = StringBuffer();
    var i = 0;
    while (i < bytes.length) {
      final b = bytes[i];
      if (b < 0x80) {
        sb.writeCharCode(b);
        i++;
        continue;
      }
      if (i + 1 >= bytes.length) {
        sb.writeCharCode(0xFFFD);
        i++;
        continue;
      }
      final cp = _reverse[(b << 8) | bytes[i + 1]];
      if (cp == null) {
        sb.writeCharCode(0xFFFD);
        i += 2;
        continue;
      }
      sb.writeCharCode(cp);
      i += 2;
    }
    return sb.toString();
  }

  /// 反查表（字节对 → 码点），首次解码时构建并缓存。
  /// 全表为双射（生成器已校验），反查无碰撞。
  static Map<int, int> get _reverse {
    return _reverseCache ??= {
      for (final e in gbkFullTable.entries) e.value: e.key,
    };
  }

  static Map<int, int>? _reverseCache;
}

/// 常用字子集通道（可选 fast path；覆盖率低于全表，字节与全表一致）。
class GbkCodec implements GbkEncoder {
  const GbkCodec({this.fallbackChar = 0x3F});

  /// 表外字符的占位字节（默认 ASCII '?'）。
  final int fallbackChar;

  @override
  bool get isGbkLike => true;

  /// 编码字符串：ASCII 原样；表内字符查 [gbkTable] 双字节；表外折 '?'。
  @override
  Uint8List encode(String s) {
    final out = BytesBuilder();
    for (final char in s.runes) {
      if (char < 0x80) {
        out.addByte(char);
      } else {
        final bytes = gbkTable[char];
        if (bytes != null) {
          out.add(bytes);
        } else {
          out.addByte(fallbackChar);
        }
      }
    }
    return out.toBytes();
  }
}

